/** Проверяет строгий ручной ввод и календарные переходы, включая мобильный числовой формат и границы года. */
import { describe, expect, it } from 'vitest';
import { dateAtUtc, moveDate, moveMonth, parseDateInput } from '../../src/client/controls/date-utils';

describe('Разбор даты', () => {
  it.each([
    ['2026-06-17', '2026-06-17'],
    ['17.06.2026', '2026-06-17'],
    ['17/06/2026', '2026-06-17'],
    ['17062026', '2026-06-17'],
    ['1.6.2026', '2026-06-01'],
    [' 01062026 ', '2026-06-01'],
    ['29.02.2024', '2024-02-29'],
    ['29022000', '2000-02-29'],
    ['0001-01-01', '0001-01-01'],
    ['31.12.9999', '9999-12-31'],
    ['01010001', '0001-01-01'],
  ])('принимает %s без зависимости от часового пояса', (input, expected) => {
    expect(parseDateInput(input)).toBe(expected);
  });

  it.each([
    '', '   ', '2026-2-03', '17.06/2026', '1706202', '170620260', '17 06 2026',
    '2026-02-29', '29021900', '31042026', '32.01.2026', '00.01.2026',
    '01.00.2026', '01.13.2026', '0000-01-01', '01010000', '10000-01-01',
    '2026-06-17T00:00:00Z', '2026-06-17abc',
  ])('отклоняет несуществующий день или неполный формат %s', input => {
    expect(parseDateInput(input)).toBeNull();
  });

  it('сохраняет ранние годы без автоматического преобразования в 1900-е', () => {
    expect(dateAtUtc('0001-01-01').toISOString()).toBe('0001-01-01T00:00:00.000Z');
    expect(dateAtUtc('0099-12-31').toISOString()).toBe('0099-12-31T00:00:00.000Z');
  });
});

describe('Смещение календарных дней', () => {
  it.each([
    ['2024-02-28', 1, '2024-02-29'],
    ['2026-02-28', 1, '2026-03-01'],
    ['2026-01-01', -1, '2025-12-31'],
    ['2026-06-17', 0, '2026-06-17'],
    ['0001-01-01', -1, ''],
    ['9999-12-31', 1, ''],
  ])('%s на %i дней даёт %s', (input, offset, expected) => {
    expect(moveDate(input, offset)).toBe(expected);
  });
});

describe('Смещение календарных месяцев', () => {
  it.each([
    ['2024-01-31', 1, '2024-02-29'],
    ['2026-01-31', 1, '2026-02-28'],
    ['2026-03-31', -1, '2026-02-28'],
    ['2026-12-31', 1, '2027-01-31'],
    ['2026-01-31', -1, '2025-12-31'],
    ['2024-02-29', 12, '2025-02-28'],
    ['2026-06-17', 0, '2026-06-17'],
    ['0001-01-01', -1, ''],
    ['9999-12-31', 1, ''],
  ])('%s на %i месяцев даёт %s', (input, offset, expected) => {
    expect(moveMonth(input, offset)).toBe(expected);
  });
});
