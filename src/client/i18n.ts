const dict: Record<Lang, Record<Key, Entry>> = { ru, en };

let current: Lang = detect();

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return 'ru';
}

export function lang(): Lang {
  return current;
}

export function setLang(next: Lang) {
  current = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* ignore */
  }
  document.dispatchEvent(new CustomEvent('langchange', { detail: next }));
}

export function t(key: Key, params: P = {}): string {
  const e = dict[current][key] ?? dict.ru[key];
  return typeof e === 'function' ? e(params) : e;
}

export function locale(): string {
  return current === 'en' ? 'en-GB' : 'ru-RU';
}

